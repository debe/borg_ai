"""Generate ledger/_generated.py from data/rates.csv."""
import csv
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(root / "data" / "rates.csv")))
body = ",\n".join(f'    ("{r["from"]}", "{r["to"]}"): "{r["rate"]}"' for r in rows)
(root / "ledger" / "_generated.py").write_text(f"# generated by tools/gen.py, do not edit\nRATES = {{\n{body},\n}}\n")
